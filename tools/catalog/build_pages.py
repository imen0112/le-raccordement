def compatible(it, all_items):
    """Fittings that go on the same pipe: same standard, steel grade and finish, and an end
    with the same outside diameter. Only real catalog references; nothing is inferred."""
    d = it['dims']
    ods = {d['d']} if 'd' in d else {d['d1'], d['d2']}
    wall = d.get('t') if 'd' in d else None
    out = []
    for x in all_items:
        if x['id'] == it['id'] or x['norme'] != it['norme'] or x['nuance'] != it['nuance'] or x['finition'] != it['finition']:
            continue
        xd = x['dims']
        if 'd' in xd:
            if xd['d'] not in ods:
                continue
            if wall is not None and xd.get('t') is not None and xd['t'] != wall:
                continue          # EN: same wall thickness on the shared pipe
            if 'sch' in d and xd.get('sch') and xd['sch'] != d['sch']:
                continue          # ASME: same schedule
        else:
            if xd['d1'] not in ods and xd['d2'] not in ods:
                continue
            if 'sch' in d and xd.get('sch') and xd['sch'] != d['sch']:
                continue
        if x['family'] == it['family'] and x['article'] == it['article']:
            continue              # same product type: already under "Other sizes"
        out.append(x)
    out.sort(key=lambda x: (FAMILY_ORDER.index(x['family']), x['articleEn'], x['typeEn'] or '', x['dims'].get('d', x['dims'].get('d1', 0)), x['dims'].get('d2', 0)))
    return out


