def size_range(items, ends=False):
    """'Ø 21.3 to 323.8 mm' and the wall thicknesses of a list of references, in the page language."""
    uniq = lambda xs: sorted(set(x for x in xs if x))
    to = t('to', 'à')
    if 'd1' in items[0]['dims']:
        d1 = [i['dims']['d1'] for i in items]; d2 = [i['dims']['d2'] for i in items]
        if ends:
            size = t('Ø %s to %s mm (large end), Ø %s to %s mm (small end)', 'Ø %s à %s mm (grand côté), Ø %s à %s mm (petit côté)')
        else:
            size = t('Large end Ø %s to %s mm, small end Ø %s to %s mm', 'Grand côté Ø %s à %s mm, petit côté Ø %s à %s mm')
        size = size % (num(min(d1)), num(max(d1)), num(min(d2)), num(max(d2)))
        walls = [w for i in items for w in (i['dims'].get('t1'), i['dims'].get('t2')) if w]
    else:
        ds = [i['dims']['d'] for i in items]
        size = 'Ø %s %s %s mm' % (num(min(ds)), to, num(max(ds)))
        walls = [i['dims']['t'] for i in items if 't' in i['dims']]
    thickness = (['%s %s %s mm' % (num(min(walls)), to, num(max(walls)))] if walls else []) + uniq(i['dims'].get('sch') for i in items)
    return size, thickness


