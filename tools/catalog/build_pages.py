def read(path):
    with open(os.path.join(ROOT, path), encoding='utf-8') as fh:
        return fh.read()


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, 'w', encoding='utf-8') as fh:
        fh.write(text)


def replace_block(text, name, content, path):
    start, end = '<!-- %s:START -->' % name, '<!-- %s:END -->' % name
    if start not in text or end not in text:
        raise SystemExit('Missing %s markers in %s' % (name, path))
    a = text.index(start) + len(start)
    b = text.index(end)
    return text[:a] + '\n' + content + '\n' + text[b:]


def deeper(fragment):
    """Re-base relative href/src of a /products/ page fragment for /products/<family>/."""
    def fix(m):
        attr, v = m.group(1), m.group(2)
        if re.match(r'^(https?:|mailto:|tel:|#|/|data:)', v):
            return m.group(0)
        return '%s="%s"' % (attr, '../' if v in ('./', '') else '../' + v)
    return re.sub(r'\b(href|src)="([^"]*)"', fix, fragment)


def image_for(it):
    a = it['article']
    if a.startswith('Coude'):
        return 'elbow-45.jpg' if '45°' in a else 'elbow-90.jpg'
    if a.startswith('Té'):
        return 'equal-tee.jpg'
    if a.startswith('RE '):
        return 'eccentric-reducer.png'
    if a.startswith('RC'):
        return 'concentric-reducer.jpg'
    return 'cap.jpg'


def key_specs(it):
    d = it['dims']
    if 'd1' in d:
        size = it['dimsLabel'] + ' mm'
    elif 't' in d:
        size = 'Ø %s × %s mm' % (num(d['d']), num(d['t']))
    else:
        size = 'Ø %s mm, %s' % (num(d['d']), d['sch'])
    rows = [('Size', e(size)), ('Standard', e(norme_label(it['norme']))), ('Grade', e(it['nuance']))]
    if it['typeEn']:
        rows.append(('Manufacturing', e(it['typeEn'])))
    rows.append(('Finish', e(it['finitionEn'])))
    return rows



def spec_rows(it):
    d = it['dims']
    rows = [('Reference', '<strong class="mono">%s</strong>' % e(it['code'])),
            ('Designation', e(it['designationEn'])),
            ('Product type', e(it['articleEn'])),
            ('Family', e(FAMILY_TEXT[it['family']]['title']))]
    if 'd1' in d:
        rows.append(('Large-end outside Ø', '%s mm' % num(d['d1'])))
        if 't1' in d:
            rows.append(('Large-end wall thickness', '%s mm' % num(d['t1'])))
        rows.append(('Small-end outside Ø', '%s mm' % num(d['d2'])))
        if 't2' in d:
            rows.append(('Small-end wall thickness', '%s mm' % num(d['t2'])))
        if 'sch' in d:
            rows.append(('Wall thickness (schedule)', e(d['sch'])))
    elif d:
        rows.append(('Outside Ø', '%s mm' % num(d['d'])))
        rows.append(('Wall thickness', ('%s mm' % num(d['t'])) if 't' in d else e(d['sch']) + ' (schedule)'))
    if it['typeEn']:
        rows.append(('Manufacturing', e(it['typeEn'])))
    rows += [
             ('Steel grade', e(it['nuance'])),
             ('Standard', e(norme_label(it['norme']))),
             ('Finish', e(it['finitionEn']))]
    return rows


def properties(it):
    d = it['dims']
    out = []
    def pv(name, value, unit=None):
        p = {'@type': 'PropertyValue', 'name': name, 'value': value}
        if unit:
            p['unitCode'] = unit  # UN/CEFACT: MMT = millimetre
        out.append(p)
    if 'd1' in d:
        pv('Large-end outside diameter', d['d1'], 'MMT')
        if 't1' in d: pv('Large-end wall thickness', d['t1'], 'MMT')
        pv('Small-end outside diameter', d['d2'], 'MMT')
        if 't2' in d: pv('Small-end wall thickness', d['t2'], 'MMT')
        if 'sch' in d: pv('Wall thickness schedule', d['sch'])
    elif d:
        pv('Outside diameter', d['d'], 'MMT')
        if 't' in d: pv('Wall thickness', d['t'], 'MMT')
        else: pv('Wall thickness schedule', d['sch'])
    if it['typeEn']: pv('Manufacturing', it['typeEn'])
    pv('Steel grade', it['nuance'])
    pv('Standard', norme_label(it['norme']))
    pv('Finish', it['finitionEn'])
    return out


