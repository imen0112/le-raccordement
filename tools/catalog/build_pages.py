def properties(it):
    d = it['dims']
    out = []
    def pv(name, value, unit=None):
        p = {'@type': 'PropertyValue', 'name': name, 'value': value}
        if unit:
            p['unitCode'] = unit  # UN/CEFACT: MMT = millimetre
        out.append(p)
    if 'd1' in d:
        pv(t('Large-end outside diameter', 'Diamètre extérieur grand côté'), d['d1'], 'MMT')
        if 't1' in d: pv(t('Large-end wall thickness', 'Épaisseur grand côté'), d['t1'], 'MMT')
        pv(t('Small-end outside diameter', 'Diamètre extérieur petit côté'), d['d2'], 'MMT')
        if 't2' in d: pv(t('Small-end wall thickness', 'Épaisseur petit côté'), d['t2'], 'MMT')
        if 'sch' in d: pv(t('Wall thickness schedule', 'Épaisseur (schedule)'), d['sch'])
    elif d:
        pv(t('Outside diameter', 'Diamètre extérieur'), d['d'], 'MMT')
        if 't' in d: pv(t('Wall thickness', 'Épaisseur'), d['t'], 'MMT')
        else: pv(t('Wall thickness schedule', 'Épaisseur (schedule)'), d['sch'])
    if it['typeEn']: pv(t('Manufacturing', 'Fabrication'), tx(it, 'type'))
    pv(t('Steel grade', 'Nuance d’acier'), it['nuance'])
    pv(t('Standard', 'Norme'), norme_label(it['norme']))
    pv(t('Finish', 'Finition'), tx(it, 'finish'))
    return out


