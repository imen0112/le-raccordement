def family_jsonld(fam, items):
    ft = FAMILY_TEXT[fam]
    url = '%s/products/%s.html' % (SITE, fam)
    data = {'@context': 'https://schema.org', '@graph': [
        {'@type': 'CollectionPage', '@id': url + '#webpage', 'url': url, 'name': 'Pipe %s, %d references' % (ft['title'], len(items)),
         'inLanguage': 'en', 'isPartOf': {'@id': SITE + '/#website'}, 'about': {'@id': SITE + '/#organization'},
         'mainEntity': {'@type': 'ItemList', 'numberOfItems': len(items), 'itemListElement': [
             {'@type': 'ListItem', 'position': i + 1, 'url': '%s/products/%s/%s.html' % (SITE, fam, it['slug']),
              'name': it['designationDisplay']} for i, it in enumerate(items)]}},
        {'@type': 'BreadcrumbList', 'itemListElement': [
            {'@type': 'ListItem', 'position': 1, 'name': 'Home', 'item': SITE + '/'},
            {'@type': 'ListItem', 'position': 2, 'name': 'Products', 'item': SITE + '/products/'},
            {'@type': 'ListItem', 'position': 3, 'name': ft['title'], 'item': url}]}]}
    return '<script type="application/ld+json">%s</script>' % json.dumps(data, ensure_ascii=False).replace('</', '<\\/')


def family_tiles(data, counts):
    out = []
    for fam in FAMILIES:
        items = data[fam]
        ft = FAMILY_TEXT[fam]
        articles = sorted(set(it['article'] for it in items))
        normes = sorted(set(norme_label(it['norme']) for it in items))
        out.append('''      <a href="%(fam)s.html" class="family-tile">
        <span class="family-tile-name">%(title)s</span>
        <span class="family-tile-count"><strong>%(n)d</strong> references</span>
        <span class="family-tile-meta">%(lead)s</span>
        <span class="family-tile-list" lang="fr">%(articles)s</span>
        <span class="family-tile-std">%(normes)s</span>
        <span class="family-tile-cta">View the list <span class="arrow">→</span></span>
      </a>''' % {'fam': fam, 'title': ft['title'], 'n': counts[fam], 'lead': e(ft['lead']),
                 'articles': ' · '.join(e(a) for a in articles), 'normes': ' · '.join(e(n) for n in normes)})
    return '    <div class="family-grid">\n%s\n    </div>' % '\n'.join(out)


def main():
    data, counts = {}, {}
    for fam in FAMILIES:
        with open(os.path.join(ROOT, 'data', 'catalog', fam + '.json'), encoding='utf-8') as fh:
            data[fam] = json.load(fh)['items']
        counts[fam] = len(data[fam])
    generated = json.load(open(os.path.join(ROOT, 'data', 'catalog', 'index.json'), encoding='utf-8'))['generated']

    sitemap_urls = []
    for fam in FAMILIES:
        path = 'products/%s.html' % fam
        page = read(path)
        page = replace_block(page, 'CATALOG', catalog_section(fam, data[fam], counts), path)
        page = replace_block(page, 'JSONLD', family_jsonld(fam, data[fam]), path)
        write(path, page)

        # Chrome of the family page, re-based one level deeper
        top = deeper(page[page.index('<body>') + len('<body>'):page.index('<main>')]).strip()
        bottom = deeper(page[page.index('</main>') + len('</main>'):page.index('<script src="../js/products.js')]).strip()
        head = page[page.index('<link rel="icon"'):page.index('</head>')]
        head_assets = '\n'.join(deeper(l) for l in head.splitlines()
                                if l.startswith(('<link rel="icon"', '<link rel="preconnect"', '<link href="https://fonts', '<link rel="stylesheet"')))

        out_dir = os.path.join(ROOT, 'products', fam)
        if os.path.isdir(out_dir):
            # Only ever remove pages this script generated
            for name in os.listdir(out_dir):
                p = os.path.join(out_dir, name)
                with open(p, encoding='utf-8') as fh:
                    if 'generated by tools/catalog/build_pages.py' not in fh.read(2000):
                        raise SystemExit('Refusing to delete non-generated file %s' % p)
            shutil.rmtree(out_dir)
        for it in data[fam]:
            write('products/%s/%s.html' % (fam, it['slug']), ref_page(it, data[fam], top, bottom, head_assets))
            sitemap_urls.append('%s/products/%s/%s.html' % (SITE, fam, it['slug']))

    idx = read('products/index.html')
    write('products/index.html', replace_block(idx, 'FAMILIES', family_tiles(data, counts), 'products/index.html'))

    sm = read('sitemap.xml')
    block = '\n'.join('  <url><loc>%s</loc><lastmod>%s</lastmod><changefreq>monthly</changefreq><priority>0.6</priority></url>' % (u, generated)
                      for u in sitemap_urls)
    write('sitemap.xml', replace_block(sm, 'REFERENCES', block, 'sitemap.xml'))
    print('Reference pages:', len(sitemap_urls), counts)


if __name__ == '__main__':
    main()
